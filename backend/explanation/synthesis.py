"""Architectural Role: Generative Explanation & Zero-Trust Citation Containment Subsystem.

This module formats retrieved academic evidence into structured prompts for Google Gemini 2.5 Flash
and validates model outputs against strict zero-trust citation boundaries.

Key Architectural Safeguards:
1. Syntactic Citation ID Containment Validator:
   - Every factual claim generated by the LLM must explicitly cite document IDs supplied in context.
   - Any claim citing fictitious or external document IDs is deterministically excised prior to UI presentation.
2. Citation Containment != Semantic Entailment:
   - Verifying that cited document IDs exist in the prompt context prevents fabricated citations,
     but does not mathematically prove that the cited publication semantically entails the assertion.
3. Deterministic Fallback:
   - If the generative model fails, times out, or produces non-JSON output, the system seamlessly
     reverts to a deterministic summary assembled directly from trusted SQLite metadata.
"""
from __future__ import annotations
"""Versioned semantic retrieval over canonical scholarly publication records.

The relational database remains authoritative. Chroma stores only a rebuildable
retrieval projection, keyed by canonical publication identity and content hash.
"""

