logger = get_logger(__name__)
INDEX_VERSION = "scholarly-record-v1"
EMBEDDING_MODEL = "all-MiniLM-L6-v2"
if os.getenv("EMBEDDING_MODEL", EMBEDDING_MODEL) != EMBEDDING_MODEL:
    raise ValueError("This Chroma embedding function supports only all-MiniLM-L6-v2")
INDEX_PATH = Path(os.getenv("VECTOR_INDEX_PATH", str(Path(__file__).resolve().parents[1] / "vector_index")))
COLLECTION_NAME = "scholarly_records_v1"
MAX_DOCUMENT_CHARS = 12000


@dataclass(frozen=True)
class ScholarlyDocument:
    id: str
    text: str
    metadata: dict[str, Any]
    content_hash: str


@dataclass(frozen=True)
class RetrievalHit:
    document_id: str
    canonical_id: str
    title: str | None
    abstract: str | None
    doi: str | None
    year: int | None
    venue: str | None
    authors: list[str]
    affiliation_mentions: list[str]
    sources: list[str]
    source_record_ids: list[str]
    source_external_ids: dict[str, list[str]]
    url: str | None
    score: float
    rank: int
    content_hash: str

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


def _json_list(value: str | None) -> list[Any]:
    if not value:
        return []
    try:
        parsed = json.loads(value)
    except (TypeError, json.JSONDecodeError):
        return []
    return parsed if isinstance(parsed, list) else []


def _stable_id(canonical_id: str) -> str:
    return "pub_" + hashlib.sha256(canonical_id.encode("utf-8")).hexdigest()


def _metadata_text(value: Any) -> str:
    if not isinstance(value, str):
        return ""
    return re.sub(r"\s+", " ", value).strip()


def _record_concepts(records: list[SourceRecord]) -> list[str]:
    found: set[str] = set()
    concept_keys = {"concepts", "topics", "x_concepts", "subject", "subjects", "keywords"}

    def visit(value: Any, key: str = "") -> None:
        if isinstance(value, dict):
            if key.casefold() in concept_keys:
                label = value.get("display_name") or value.get("name") or value.get("term")
                if isinstance(label, str) and label.strip():
                    found.add(_metadata_text(label))
            for child_key, child in value.items():
                visit(child, str(child_key))
        elif isinstance(value, list):
            for item in value:
                visit(item, key)
        elif key.casefold() in concept_keys and isinstance(value, str) and value.strip():
            found.add(_metadata_text(value))

    for record in records:
        try:
            visit(json.loads(record.raw_json or "{}"))
        except (TypeError, json.JSONDecodeError):
            continue
    return sorted(found)[:100]


def _record_affiliations(records: list[SourceRecord]) -> list[str]:
    """Extract publication affiliation mentions without assigning them to an author."""
    found: set[str] = set()
    affiliation_keys = {"affiliation", "affiliations", "institution", "institutions"}

    def visit(value: Any, key: str = "") -> None:
        if key.casefold() not in affiliation_keys:
            if isinstance(value, dict):
                for child_key, child in value.items():
                    visit(child, str(child_key))
            elif isinstance(value, list):
                for item in value:
                    visit(item, key)
            return
        if isinstance(value, str) and value.strip():
            found.add(_metadata_text(value))
        elif isinstance(value, dict):
            label = value.get("display_name") or value.get("name") or value.get("institution_name")
            if isinstance(label, str) and label.strip():
                found.add(_metadata_text(label))
            for child_key, child in value.items():
                visit(child, str(child_key))
        elif isinstance(value, list):
            for item in value:
                visit(item, key)

    for record in records:
        try:
            visit(json.loads(record.raw_json or "{}"))
        except (TypeError, json.JSONDecodeError):
            continue
    return sorted(found)[:100]


def build_document(publication: Publication, source_records: list[SourceRecord]) -> ScholarlyDocument | None:
    """Build a deterministic index document without inventing missing fields."""
    canonical_id = _metadata_text(publication.canonical_id)
    title = _metadata_text(publication.title)
    if not canonical_id or not title:
        return None
    authors_raw = _json_list(publication.authors)
    authors = [str(item).strip() for item in authors_raw if isinstance(item, str) and item.strip()]
    sources = sorted({str(s).strip() for s in _json_list(publication.source_list) if isinstance(s, str) and s.strip()})
    source_ids: list[str] = []
    if source_records:
        sources = sorted(set(sources) | {record.source for record in source_records if record.source})
        source_ids = sorted({str(record.id) for record in source_records})
    abstract = _metadata_text(publication.abstract) or None
    venue = _metadata_text(publication.venue) or None
    doi = _metadata_text(publication.doi) or None
    author_text = ", ".join(authors)
    concepts = _record_concepts(source_records)
    affiliations = _record_affiliations(source_records)
    content_parts = [f"Title: {title}"]
    if abstract:
        content_parts.append(f"Abstract: {abstract}")
    if author_text:
        content_parts.append(f"Authors: {author_text}")
    if venue:
        content_parts.append(f"Venue: {venue}")
    if concepts:
        content_parts.append(f"Topics: {', '.join(concepts)}")
    if affiliations:
        content_parts.append(f"Publication affiliation mentions: {', '.join(affiliations)}")
    if publication.year:
        content_parts.append(f"Year: {publication.year}")
    text = "\n".join(content_parts)[:MAX_DOCUMENT_CHARS]
    url = next((record.url for record in source_records if record.url), None)
    source_external_ids: dict[str, list[str]] = {}
    for record in source_records:
        if record.source and record.source_id:
            source_external_ids.setdefault(record.source, []).append(record.source_id)
    source_external_ids = {source: sorted(set(ids)) for source, ids in source_external_ids.items()}
    source_ingested_at = max((record.ingested_at for record in source_records if record.ingested_at), default=None)
    source_ingested_at = source_ingested_at.isoformat() if source_ingested_at else ""
    metadata_base: dict[str, Any] = {
        "canonical_id": canonical_id,
        "publication_id": str(publication.id),
        "source_providers": json.dumps(sources, ensure_ascii=False),
        "primary_source": (publication.best_source or (sources[0] if sources else "")).casefold(),
        "source_record_ids": json.dumps(source_ids, ensure_ascii=False),
        "source_external_ids": json.dumps(source_external_ids, ensure_ascii=False),
        "source_ingested_at": source_ingested_at,
        "title": title,
        "abstract": abstract or "",
        "abstract_source": publication.abstract_source or "",
        "doi": doi or "",
        "year": publication.year if publication.year is not None else -1,
        "venue": venue or "",
        "authors": json.dumps(authors, ensure_ascii=False),
        "concepts": json.dumps(concepts, ensure_ascii=False),
        "affiliation_mentions": json.dumps(affiliations, ensure_ascii=False),
        "url": url or "",
    }
    fingerprint = {"text": text, "metadata": metadata_base, "index_version": INDEX_VERSION, "embedding_model": EMBEDDING_MODEL}
    content_hash = hashlib.sha256(json.dumps(fingerprint, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()
    metadata: dict[str, Any] = {**metadata_base, "content_hash": content_hash, "index_version": INDEX_VERSION, "embedding_model": EMBEDDING_MODEL}
    return ScholarlyDocument(_stable_id(canonical_id), text, metadata, content_hash)


def _chroma_collection(path: Path = INDEX_PATH):
    import chromadb
    from chromadb.utils.embedding_functions import DefaultEmbeddingFunction
    from chromadb.utils.embedding_functions.onnx_mini_lm_l6_v2 import ONNXMiniLM_L6_V2

    path.mkdir(parents=True, exist_ok=True)
    client = chromadb.PersistentClient(path=str(path))
    # Chroma's default ONNX Sentence Transformers model otherwise writes under
    # Path.home(). Keep both the model cache and index in the configured path.
    ONNXMiniLM_L6_V2.DOWNLOAD_PATH = path / "model_cache" / EMBEDDING_MODEL
    collection = client.get_or_create_collection(
        COLLECTION_NAME,
        metadata={"index_version": INDEX_VERSION, "embedding_model": EMBEDDING_MODEL, "hnsw:space": "cosine"},
        embedding_function=DefaultEmbeddingFunction(),
    )
    return client, collection


def index_status(path: Path = INDEX_PATH) -> dict[str, Any]:
    """Inspect persisted collection state without loading embeddings or a model."""
    if not path.exists():
        return {"status": "not_built", "document_count": 0, "index_version": INDEX_VERSION, "embedding_model": EMBEDDING_MODEL}
    try:
        import chromadb

        client = chromadb.PersistentClient(path=str(path))
        try:
            collection = client.get_collection(COLLECTION_NAME)
        except Exception:
            return {"status": "not_built", "document_count": 0, "index_version": INDEX_VERSION, "embedding_model": EMBEDDING_MODEL}
        count = collection.count()
        return {"status": "ready" if count else "empty", "document_count": count, "index_version": INDEX_VERSION, "embedding_model": EMBEDDING_MODEL}
    except Exception as exc:
        logger.warning("Vector index status check failed (%s)", type(exc).__name__)
        return {"status": "unavailable", "document_count": 0, "index_version": INDEX_VERSION, "embedding_model": EMBEDDING_MODEL}


