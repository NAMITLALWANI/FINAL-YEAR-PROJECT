"""LaTeX result tables generated directly from a C7 report (`metrics_c7.evaluate_primary`), so that every number in the paper's Results section is traceable to a frozen
artifact and none is typed by hand. Pure functions; no data access.

Rules: tables are produced only from a report; a final table needs every protocol parameter to be specified (otherwise `draft=True` is required and the output is
marked as a draft); verified tables show a placeholder when verification is incomplete; intervals that were withheld are shown with the reason, never invented;
verified and benchmark-derived results are in separate tables and are never combined.
"""
from __future__ import annotations

from typing import Any, Mapping, Sequence

STRATA = ("S", "M", "L", "XL")


class TableError(ValueError):
    """The report cannot yet support the requested table."""


def esc(text: Any) -> str:
    out = str(text)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")):
        out = out.replace(a, b)
    return out


def pct(v: float | None) -> str:
    return "--" if v is None else f"{100 * v:.1f}\\%"


def frac(n: Any, d: Any) -> str:
    return f"{int(n)}/{int(d)}"


def interval(iv: Sequence[float] | None) -> str:
    return "" if not iv else f" [{100 * iv[0]:.1f}, {100 * iv[1]:.1f}]"


def _cell(entry: Mapping[str, Any]) -> str:
    if entry["n_h"] == 0:
        return "unsampled"
    return f"{frac(entry['numerator'], entry['denominator'])} ({pct(entry['value'])})"


def _pooled(p: Mapping[str, Any]) -> str:
    if p.get("point") is None:
        return "--"
    base = pct(p["point"])
    if p.get("interval"):
        return base + interval(p["interval"])
    status = str(p.get("interval_status", ""))
    code = ("R3, counts only" if p.get("regime") == "R3" else "census" if status.startswith("none") else "interval withheld")
    return f"{base} ({code})"


def _check(report: Mapping[str, Any], draft: bool) -> list[str]:
    unspecified = [k for k, v in report["parameters"].items() if v["status"] == "unspecified"]
    if unspecified and not draft:
        raise TableError(f"parameters not specified before freeze: {unspecified}; pass draft=True to produce draft tables")
    return unspecified


def _table(caption: str, label: str, colspec: str, header: Sequence[str], rows: Sequence[Sequence[str]], *, draft: bool, wide: bool = True) -> str:
    env = "table*" if wide else "table"
    cap = esc(caption) + (r" \textbf{DRAFT: parameters not yet frozen.}" if draft else "")
    lines = [f"% generated by hammer_pilot.paper_tables from a C7 report; do not edit by hand", rf"\begin{{{env}}}[t]", rf"\caption{{{cap}}}", rf"\label{{{label}}}", r"\centering\footnotesize",
             rf"\begin{{tabular}}{{{colspec}}}", r"\toprule", " & ".join(rf"\textbf{{{esc(h)}}}" for h in header) + r" \\", r"\midrule"]
    lines += [" & ".join(r) + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}", rf"\end{{{env}}}"]
    return "\n".join(lines) + "\n"


def _metric_rows(section: Mapping[str, Any], names: Sequence[tuple[str, str]], estimand: str) -> list[list[str]]:
    rows = []
    for key, label in names:
        q = section[key]
        rows.append([esc(label)] + [_cell(q["per_stratum"][s]) if s in q["per_stratum"] else "--" for s in STRATA] + [_pooled(q["pooled"][estimand])])
    return rows


def table_case_accounting(report: Mapping[str, Any], *, draft: bool) -> str:
    acc = report["case_accounting"]
    rows = [[esc(o.replace("_", " "))] + [str(acc["outcome_by_stratum"].get(s, {}).get(o, 0)) for s in STRATA] + [str(acc["outcome_counts"][o])] for o in acc["outcome_counts"]]
    rows.append([r"\textit{cases drawn}"] + [str(acc["strata"].get(s, {}).get("n_h", 0)) for s in STRATA] + [str(acc["n_primary"])])
    rows.append([r"\textit{frame size}"] + [str(acc["strata"].get(s, {}).get("N_h", "--")) for s in STRATA] + [""])
    classes = ", ".join(f"{esc(k.replace('_', ' '))} {v}" for k, v in acc["reporting_class_counts"].items())
    return _table(f"Case accounting of the primary sample by stratum. Reporting classes: {classes}; secondary cases excluded: {acc['n_secondary_excluded']}.", "tab:res-accounting",
                  "lrrrrr", ["Outcome", *STRATA, "All"], rows, draft=draft)


def table_retrieval(report: Mapping[str, Any], *, draft: bool, estimand: str = "E1") -> str:
    names = [("pool_mapping_rate", "Pool mapping rate"), ("end_to_end_success_at_1", "End-to-end success@1"), ("end_to_end_success_at_5", "End-to-end success@5"),
             ("end_to_end_success_at_10", "End-to-end success@10"), ("end_to_end_mrr", "End-to-end MRR"), ("conditional_recall_at_1", "Conditional recall@1"),
             ("conditional_recall_at_5", "Conditional recall@5"), ("conditional_recall_at_10", "Conditional recall@10"), ("conditional_mrr", "Conditional MRR")]
    rows = _metric_rows(report["retrieval_benchmark_derived"], [(k, l) for k, l in names if k in report["retrieval_benchmark_derived"]], estimand)
    return _table(f"Benchmark-derived retrieval on the R2 pool (ORCID agreement, not independently verified). Cells are numerator/denominator (rate); the last column is the pooled {estimand} estimate. End-to-end uses all cases; conditional uses cases with a mapped profile.",
                  "tab:res-retrieval", "lrrrrr", ["Measure", *STRATA, f"Pooled {estimand}"], rows, draft=draft)


def table_selective(report: Mapping[str, Any], *, draft: bool, estimand: str = "E1") -> str:
    lf = report["label_free"]
    rows = _metric_rows(lf, [(k, k.replace("rate_", "").replace("_", " ")) for k in lf], estimand)
    bm = report["selective_benchmark_derived"]
    rows += _metric_rows(bm, [("benchmark_automatic_precision", "Automatic precision (benchmark-derived)")], estimand)
    return _table("Outcome categories over all cases (label-free) and benchmark-derived automatic precision. Benchmark-derived precision is not verified accuracy.",
                  "tab:res-selective", "lrrrrr", ["Measure", *STRATA, f"Pooled {estimand}"], rows, draft=draft)


def table_verified(report: Mapping[str, Any], *, draft: bool, estimand: str = "E1") -> str:
    sv = report["selective_verified"]
    if not sv["scoring"]["verification_complete"]:
        n = sv["scoring"]["status_counts"]["unverified"]
        return _table("Verified automatic precision of the primary pair. Verification is incomplete, so no verified rate is reported.", "tab:res-verified", "lr", ["Status", "Automatic assignments"],
                      [["unverified", str(n)], ["total automatic", str(sv["scoring"]["automatic_assignments"])]], draft=draft, wide=False)
    est = sv["estimates"]
    rows = _metric_rows(est, [("verified_automatic_precision", "Precision (definite labels)"), ("verified_selective_risk", "Selective risk"),
                              ("verified_precision_all_wrong", "Bracket: uncertain counted wrong"), ("verified_precision_all_right", "Bracket: uncertain counted right")], estimand)
    sc = sv["scoring"]["status_counts"]
    cap = (f"Verified automatic precision of the primary pair (independent labels). Scored correct {sc['correct']}, incorrect {sc['incorrect']}, uncertain {sc['uncertain']}, "
           f"unverifiable {sc['unverifiable']}. Pooled column: {estimand}; sparse counts are shown without a bootstrap interval.")
    return _table(cap, "tab:res-verified", "lrrrrr", ["Measure", *STRATA, f"Pooled {estimand}"], rows, draft=draft)


def table_audit(report: Mapping[str, Any], *, draft: bool) -> str:
    a = report["audit_label_error"]
    gv = a["group_validity"]
    er = a["error_rate"]
    rows = [["Audited cases", str(a["audited"])], ["Contradicted / consistent / indeterminate", f"{a['contradicted']} / {a['consistent']} / {a['indeterminate']}"],
            ["Label-error rate (definite labels)", f"{frac(er['numerator'], er['denominator'])} ({pct(er['value'])}{interval(er['ci95_exact'])})"],
            ["Bracket: all right / all wrong", f"{pct(a['bracket']['all_right']['value'])} / {pct(a['bracket']['all_wrong']['value'])}"],
            ["Reasons (cases may overlap)", ", ".join(f"{esc(k.replace('_', ' '))} {v}" for k, v in a["reason_counts"].items())],
            ["Group purity (pure / impure / unresolved)", f"{gv['purity_counts']['pure']} / {gv['purity_counts']['impure']} / {gv['purity_counts']['unresolved']}"],
            ["Impure groups outside the definite denominator", str(gv["impure_outside_definite_label_denominator"])]]
    return _table("Audit of benchmark labels in the sampled non-automatic frame of the primary pair. It describes this frame only and is not a correction factor.", "tab:res-audit",
                  "lr", ["Quantity", "Value"], rows, draft=draft, wide=False)


def table_verified_retrieval(report: Mapping[str, Any], *, draft: bool) -> str:
    rows = []
    for subset, r in report["verified_retrieval"].items():
        used = r["resolved_cases_used"]
        def bounds(x: Mapping[str, Any]) -> str:
            return f"{pct(x['lower']['value'])}--{pct(x['upper']['value'])}"
        rows.append([esc(subset.replace("_", " ")), str(used), bounds(r["mapping_rate"]), bounds(r["end_to_end_success_at_1"]), bounds(r["end_to_end_success_at_10"]),
                     str(r["judgment_categories"]["verified_same_in_pool"])])
    return _table("Verified retrieval by subset (lower--upper bounds for cannot-tell candidates). Subsets are never pooled with each other or with benchmark-derived retrieval.",
                  "tab:res-verified-retrieval", "lrrrrr", ["Subset", "Cases used", "Mapping", "Success@1", "Success@10", "Verified-same cases"], rows, draft=draft)


def table_agreement(agreement: Mapping[str, Any], *, draft: bool) -> str:
    rows = []
    for key, label in (("stage_a_status", "Stage A status"), ("stage_a_purity", "Stage A group purity"), ("stage_b_judgment", "Stage B candidate judgment")):
        a = agreement[key]
        k = "undefined" if a["kappa"] is None else f"{a['kappa']:.2f}"
        rows.append([label, str(a["n"]), f"{a.get('agreements', 0)}/{a['n']}", pct(a["raw_agreement"]), k])
    return _table("Agreement between the two independent reviewers (counts shown because kappa is unstable at small n).", "tab:res-agreement", "lrrrr",
                  ["Judgment", "Pairs", "Agreements", "Raw agreement", "Cohen's kappa"], rows, draft=draft, wide=False)


def table_parameters(report: Mapping[str, Any], *, draft: bool) -> str:
    rows = [[esc(k.replace("_", " ")), esc(v["value"]), esc(v["status"])] for k, v in report["parameters"].items()]
    return _table("Inference parameters used for this report and their status at the time of analysis.", "tab:res-parameters", "lll", ["Parameter", "Value", "Status"], rows, draft=draft, wide=False)


def render_all(report: Mapping[str, Any], *, draft: bool, agreement: Mapping[str, Any] | None = None, estimand: str = "E1") -> dict[str, str]:
    """All tables as {file name: LaTeX}. Raises TableError if a final (non-draft) table is requested while a parameter is unspecified."""
    _check(report, draft)
    out = {"res_accounting.tex": table_case_accounting(report, draft=draft), "res_retrieval.tex": table_retrieval(report, draft=draft, estimand=estimand),
           "res_selective.tex": table_selective(report, draft=draft, estimand=estimand), "res_verified.tex": table_verified(report, draft=draft, estimand=estimand),
           "res_audit.tex": table_audit(report, draft=draft), "res_verified_retrieval.tex": table_verified_retrieval(report, draft=draft),
           "res_parameters.tex": table_parameters(report, draft=draft)}
    if agreement is not None:
        out["res_agreement.tex"] = table_agreement(agreement, draft=draft)
    return out
